function retiredLocalEnvironmentPath(environmentPath) {
  return `${environmentPath}.retired`;
}

export function ensureLocalEnvironment(environmentPath = localEnvironmentPath, root = repositoryRoot) {
  if (!existsSync(environmentPath)) {
    const values = missingGeneratedValues({}, root);
    writeFileSync(environmentPath, renderLocalEnvironment(values), { mode: 0o600, flag: 'wx' });
    console.log(`Created ${path.basename(environmentPath)} with random local-only credentials and checkout-specific ports.`);
  } else {
    const current = readFileSync(environmentPath, 'utf8');
    const existing = parseEntries(current);
    archiveRetiredEnvironmentValues(environmentPath, existing);
    const active = Object.fromEntries(
      Object.entries(existing).filter(([key]) => !retiredEnvironmentKeys.has(key)),
    );
    const values = { ...active, ...missingGeneratedValues(active, root) };
    const normalized = renderLocalEnvironment(values);
    if (current !== normalized) {
      writeLocalEnvironmentAtomically(environmentPath, normalized);
      console.log(`Updated ${path.basename(environmentPath)} to the current documented layout; existing values were preserved.`);
    } else {
      console.log(`Using existing ${path.basename(environmentPath)}.`);
    }
  }
  if (process.platform !== 'win32') chmodSync(environmentPath, 0o600);
  return readLocalEnvironment(environmentPath);
}

export function readLocalEnvironment(environmentPath = localEnvironmentPath) {
  return parseLocalEnvironment(readFileSync(environmentPath, 'utf8'));
}

export function parseLocalEnvironment(content) {
  const values = parseEntries(content);
  for (const key of requiredKeys) {
    if (!values[key]) throw new Error(`Local environment is missing ${key}`);
  }
  return values;
}

export function federatedAuthenticationEnvironment(values) {
  const present = federatedKeys.filter(key => values[key] !== undefined);
  const disabled = reason => ({
    enabled: false,
    reason,
    environment: Object.fromEntries(federatedKeys.map(key => [key, ''])),
  });
  if (present.length === 0) return disabled('GitHub OAuth App is not configured');
  if (present.length !== federatedKeys.length) return disabled('GitHub OAuth App configuration is incomplete');
  if (!values.TASKPILOT_GITHUB_CLIENT_ID || !values.TASKPILOT_GITHUB_CLIENT_SECRET) {
    return disabled('GitHub OAuth App client id and client secret must be non-empty');
  }
  if (!validCallback(values.TASKPILOT_GITHUB_CALLBACK_URI)) {
    return disabled('GitHub callback must be the exact Core API loopback callback');
  }
  const hmac = decode32(values.TASKPILOT_FEDERATED_HMAC_KEY_BASE64);
  const aead = decode32(values.TASKPILOT_FEDERATED_AEAD_KEY_BASE64);
  if (!hmac || !aead) return disabled('Federated HMAC and AEAD keys must each decode to 32 bytes');
  if (hmac.equals(aead)) return disabled('Federated HMAC and AEAD keys must be independent');
  return {
    enabled: true,
    reason: 'GitHub OAuth App configuration is complete',
    environment: Object.fromEntries(federatedKeys.map(key => [key, values[key]])),
  };
}

function validCallback(value) {
  try {
    const uri = new URL(value);
    return uri.protocol === 'http:' && uri.hostname === '127.0.0.1' && Number(uri.port) >= 1024
      && Number(uri.port) <= 65535 && uri.pathname === '/desktop/v1/auth/federated/github/callback'
      && uri.search === '' && uri.hash === '' && uri.username === '' && uri.password === '';
  } catch {
    return false;
  }
}

function decode32(value) {
  try {
    const decoded = Buffer.from(value, 'base64');
    return decoded.length === 32 && decoded.toString('base64') === value ? decoded : null;
  } catch {
    return null;
  }
}

function parseEntries(content) {
  const values = {};
  for (const [lineNumber, rawLine] of content.split(/\r?\n/).entries()) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator <= 0) throw new Error(`Invalid local environment entry on line ${lineNumber + 1}`);
    const key = line.slice(0, separator).trim();
    const value = line.slice(separator + 1).trim();
    const blankAllowed = githubCredentialKeys.includes(key);
    if (!/^TASKPILOT_[A-Z0-9_]+$/.test(key) || (!value && !blankAllowed) || values[key] !== undefined) {
      throw new Error(`Invalid local environment entry on line ${lineNumber + 1}`);
    }
    values[key] = value;
  }
  return values;
}

function missingGeneratedValues(values, root) {
  const settings = defaultLocalSettings(root);
  const additions = {};
  if (!values.TASKPILOT_POSTGRES_PASSWORD) additions.TASKPILOT_POSTGRES_PASSWORD = randomBytes(24).toString('base64url');
  if (!values.TASKPILOT_REDIS_PASSWORD) additions.TASKPILOT_REDIS_PASSWORD = randomBytes(24).toString('base64url');
  if (!values.TASKPILOT_AUTH_TOKEN_PEPPER_BASE64) additions.TASKPILOT_AUTH_TOKEN_PEPPER_BASE64 = randomBytes(32).toString('base64');
  if (!values.TASKPILOT_AUTH_LEGAL_LOCALES) additions.TASKPILOT_AUTH_LEGAL_LOCALES = 'zh-CN,en';
  if (!values.TASKPILOT_FEDERATED_HMAC_KEY_BASE64) additions.TASKPILOT_FEDERATED_HMAC_KEY_BASE64 = randomBytes(32).toString('base64');
  if (!values.TASKPILOT_FEDERATED_AEAD_KEY_BASE64) additions.TASKPILOT_FEDERATED_AEAD_KEY_BASE64 = randomBytes(32).toString('base64');
  for (const [key, value] of Object.entries(settings)) if (!values[key]) additions[key] = value;
  if (!values.TASKPILOT_GITHUB_CALLBACK_URI) {
    additions.TASKPILOT_GITHUB_CALLBACK_URI = `http://127.0.0.1:${values.TASKPILOT_CORE_API_PORT ?? additions.TASKPILOT_CORE_API_PORT ?? settings.TASKPILOT_CORE_API_PORT}/desktop/v1/auth/federated/github/callback`;
  }
  for (const key of githubCredentialKeys) if (values[key] === undefined) additions[key] = '';
  return additions;
}

function commentLines(lines) {
  return lines.map(line => `# ${line}`);
}

function renderSection(section, values) {
  return [
    '# =============================================================================',
    `# ${section.title}`,
    '# =============================================================================',
    ...commentLines(section.introduction),
    '',
    ...section.fields.flatMap((field, index) => [
      ...(index > 0 ? [''] : []),
      ...commentLines(field.comments),
      `${field.key}=${values[field.key] ?? ''}`,
    ]),
  ];
}

export function exampleLocalEnvironment() {
  const values = Object.fromEntries(
    localEnvironmentSections.flatMap(section => section.fields.map(field => [field.key, field.example])),
  );
  return renderLocalEnvironment(values, {
    header: [
      'Template for TaskPilot local development.',
      '`pnpm bootstrap` creates `.env.local` with generated secrets and checkout-specific values.',
      'Copying this file manually is optional. Never put real secrets in this example.',
    ],
  });
}

export function renderLocalEnvironment(values, options = {}) {
  const header = options.header ?? [
    'Generated and maintained by `pnpm bootstrap` for local development only.',
    'This file is Git-ignored. Do not commit it or share its secrets.',
  ];
  const additional = Object.entries(values).filter(
    ([key]) => !managedEnvironmentKeys.has(key) && !retiredEnvironmentKeys.has(key),
  );
  return [
    ...commentLines(header),
    '',
    ...localEnvironmentSections.flatMap((section, index) => [
      ...(index > 0 ? ['', ''] : []),
      ...renderSection(section, values),
    ]),
    ...(additional.length > 0 ? [
      '',
      '',
      '# =============================================================================',
      '# Additional local settings',
      '# =============================================================================',
      '# Preserved verbatim because `pnpm bootstrap` does not manage these keys.',
      '',
      ...additional.map(([key, value]) => `${key}=${value}`),
    ] : []),
    '',
  ].join('\n');
}

function renderRetiredEnvironment(values) {
  return [
    '# Retired TaskPilot local settings retained only to avoid discarding previous values.',
    '# The current GitHub-login development stack does not read this file.',
    '# Delete it manually when you no longer need the old email-authentication values.',
    '',
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n');
}

function archiveRetiredEnvironmentValues(environmentPath, values) {
  const retired = Object.fromEntries(
    Object.entries(values).filter(([key]) => retiredEnvironmentKeys.has(key)),
  );
  if (Object.keys(retired).length === 0) return;
  const archivePath = retiredLocalEnvironmentPath(environmentPath);
  let archived = {};
  if (existsSync(archivePath)) archived = parseEntries(readFileSync(archivePath, 'utf8'));
  for (const [key, value] of Object.entries(retired)) {
    if (archived[key] !== undefined && archived[key] !== value) {
      throw new Error(`Retired local setting ${key} differs from ${path.basename(archivePath)}; values were not changed`);
    }
    archived[key] = value;
  }
  writeLocalEnvironmentAtomically(archivePath, renderRetiredEnvironment(archived));
  if (process.platform !== 'win32') chmodSync(archivePath, 0o600);
}

function writeLocalEnvironmentAtomically(environmentPath, content) {
  const temporaryPath = `${environmentPath}.tmp-${process.pid}-${Date.now()}`;
  try {
    writeFileSync(temporaryPath, content, { mode: 0o600, flag: 'wx' });
    if (process.platform !== 'win32') chmodSync(temporaryPath, 0o600);
    renameSync(temporaryPath, environmentPath);
  } finally {
    if (existsSync(temporaryPath)) unlinkSync(temporaryPath);
  }
}
